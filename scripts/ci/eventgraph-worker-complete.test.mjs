import test from "node:test";
import assert from "node:assert/strict";
import { handleWorkerCompletion } from "./eventgraph-worker-complete.mjs";
import { parseWorkerMarker, verifySuccessfulWorkerRun } from "./eventgraph-work-queue-guards.mjs";

const repository = "jboone1989/EventGraph";
// Sanitized fields from the real successful native Worker run 41126279153.
const run = {
  id: 41126279153,
  workflow_id: 401548383,
  name: "gh-aw work-queue d_0a8c26724a8138ad7c8c0ace75f61fadd06bca9cc97cb66c4d598dc7099c0277_1",
  path: ".github/workflows/eventgraph-worker.lock.yml",
  event: "workflow_dispatch",
  status: "completed",
  conclusion: "success",
  repository: { full_name: repository },
  head_repository: { full_name: repository },
};
const otherRun = { ...run, id: 41126279999 };

const workId = "070d0c4f897da5a1055577e095aaf445c8655d6c804870f2860cd5d2c5dc0b55";
const otherWorkId = "1".repeat(64);

function trustedFooterBody(runId = run.id, workflow = "eventgraph-worker", work = workId) {
  return [
    "## Delivery",
    "Focused tests passed.",
    "",
    `> Generated by [EventGraph GH-AW Worker](https://github.com/${repository}/actions/runs/${runId}) · claude · glm53`,
    `> Work \`${work}\` · Claim \`c_example_1\``,
    "",
    `<!-- gh-aw-workflow-id: ${workflow} -->`,
    `<!-- gh-aw-execution: {"version":1,"repository":"${repository}","aw_workflow_id":"${workflow}","run_id":"${runId}"} -->`,
  ].join("\n");
}

function pullRequest(number = 42, body = trustedFooterBody()) {
  return {
    number, state: "open", draft: false, labels: [{ name: "agent-work" }],
    base: { ref: "develop", repo: { full_name: repository } },
    head: { ref: `agent/acceptance-${number}`, sha: "a".repeat(40), repo: { full_name: repository } },
    body,
  };
}

test("a native Worker with a dynamic run-name advances the no-PR queue", () => {
  const calls = [];
  const result = handleWorkerCompletion({ action: "completed", workflow_run: run }, {
    getOpenAgentWorkPrs: () => [],
    dispatchGate: () => calls.push("gate"),
    dispatchProjectOps: () => calls.push("project-ops"),
  });
  assert.equal(result, "gate-dispatched");
  assert.deepEqual(calls, ["gate", "project-ops"]);
});

test("a successful run whose PR is missing never gets Check, but the queue continues", () => {
  // No-write Works legitimately finish without a PR; a code Work whose PR
  // vanished surfaces through this same loud warning plus queue state.
  const calls = [];
  assert.equal(handleWorkerCompletion({ action: "completed", workflow_run: run }, {
    getOpenAgentWorkPrs: () => [pullRequest(43, trustedFooterBody(otherRun.id, "eventgraph-worker", otherWorkId))],
    verifySuccessfulWorkerRun: () => assert.fail("An unmatched run must not be API-verified for Check"),
    dispatchCheck: () => calls.push("check"),
    dispatchGate: () => calls.push("gate"),
    dispatchProjectOps: () => calls.push("project-ops"),
  }), "gate-dispatched");
  assert.deepEqual(calls, ["gate", "project-ops"]);
});

test("wrong workflow, repository, event and lifecycle identities cannot advance", () => {
  for (const changed of [
    { workflow_id: 401548384 }, { path: ".github/workflows/check.yml" },
    { repository: { full_name: "someone/EventGraph" } },
    { head_repository: { full_name: "someone/EventGraph" } },
    { event: "push" }, { status: "in_progress" },
  ]) {
    assert.throws(() => handleWorkerCompletion({ action: "completed", workflow_run: { ...run, ...changed } }, {
      getOpenAgentWorkPrs: () => assert.fail("Rejected events must not access PRs"),
    }), /Unexpected workflow_run/);
  }
  assert.throws(() => handleWorkerCompletion({ action: "requested", workflow_run: run }), /Unexpected workflow_run/);
});

test("trusted GH-AW footer provenance supplies the Work and Worker run marker", () => {
  assert.deepEqual(parseWorkerMarker(trustedFooterBody()), { workId, runId: String(run.id) });
});

test("legacy explicit marker remains accepted for already-open agent PRs", () => {
  const body = `<!-- eventgraph-work-id:${workId} worker-run-id:${run.id} -->`;
  assert.deepEqual(parseWorkerMarker(body), { workId, runId: String(run.id) });
});

test("with two open PRs only the PR matching this exact run receives Check", () => {
  const mine = pullRequest(42, trustedFooterBody(run.id));
  const theirs = pullRequest(43, trustedFooterBody(otherRun.id, "eventgraph-worker", otherWorkId));
  const calls = [];
  assert.equal(handleWorkerCompletion({ action: "completed", workflow_run: run }, {
    getOpenAgentWorkPrs: () => [mine, theirs],
    verifySuccessfulWorkerRun: id => {
      calls.push(["verify", id]);
      return verifySuccessfulWorkerRun(id, () => run);
    },
    dispatchCheck: current => calls.push(["check", current.number, current.head.sha]),
    dispatchGate: () => assert.fail("A matched live PR must not trigger the gate"),
    dispatchProjectOps: () => calls.push(["project-ops"]),
  }), "check-dispatched");
  assert.deepEqual(calls, [["verify", run.id], ["check", 42, mine.head.sha], ["project-ops"]]);
});

test("two PRs claiming one run, marker-less PRs and draft PRs cannot dispatch Check", () => {
  const calls = [];
  for (const prs of [
    [pullRequest(42, trustedFooterBody()), pullRequest(43, trustedFooterBody())],
    [{ ...pullRequest(42), draft: true }],
  ]) {
    assert.throws(() => handleWorkerCompletion({ action: "completed", workflow_run: run }, {
      getOpenAgentWorkPrs: () => prs,
      verifySuccessfulWorkerRun: () => calls.push("verify"),
      dispatchCheck: () => calls.push("check"),
      dispatchGate: () => calls.push("gate"),
      dispatchProjectOps: () => calls.push("project-ops"),
    }), /matches 2 open|violates|no valid/);
    assert.deepEqual(calls, []);
  }
});

test("untrusted or inconsistent generated footer provenance is rejected", () => {
  for (const body of [
    trustedFooterBody(run.id, "other-worker"),
    trustedFooterBody().replace(`> Work \`${workId}\` · Claim \`c_example_1\`\n`, ""),
    trustedFooterBody().replace(`"run_id":"${run.id}"`, '"run_id":"123"'),
    trustedFooterBody().replace(`"repository":"${repository}"`, '"repository":"someone/EventGraph"'),
  ]) {
    assert.equal(parseWorkerMarker(body), null);
  }
});

test("a failed Worker run with an open PR fails closed; without a PR it requests the gate", () => {
  const failure = { ...run, conclusion: "failure" };
  const calls = [];
  assert.throws(() => handleWorkerCompletion({ action: "completed", workflow_run: failure }, {
    getOpenAgentWorkPrs: () => [pullRequest(42, trustedFooterBody())],
    dispatchGate: () => calls.push("gate"),
  }), /still has open agent-work PR #42/);
  assert.deepEqual(calls, []);
  assert.equal(handleWorkerCompletion({ action: "completed", workflow_run: failure }, {
    getOpenAgentWorkPrs: () => [],
    dispatchGate: () => calls.push("gate"),
    dispatchProjectOps: () => calls.push("project-ops"),
  }), "gate-dispatched");
  assert.deepEqual(calls, ["gate", "project-ops"]);
});

test("closing an agent-work PR frees its slot through the gate; other closes are ignored", () => {
  const calls = [];
  const closedEvent = { action: "closed", pull_request: { number: 42, labels: [{ name: "agent-work" }] } };
  assert.equal(handleWorkerCompletion(closedEvent, {
    dispatchGate: () => calls.push("gate"),
    dispatchProjectOps: () => calls.push("project-ops"),
  }), "gate-dispatched");
  assert.deepEqual(calls, ["gate", "project-ops"]);
  assert.equal(handleWorkerCompletion(
    { action: "closed", pull_request: { number: 7, labels: [{ name: "bug" }] } },
    { dispatchGate: () => calls.push("gate") },
  ), "ignored-non-agent-close");
  assert.deepEqual(calls, ["gate", "project-ops"]);
});

test("API verification accepts dynamic names but rejects wrong IDs and unsuccessful runs", () => {
  assert.equal(verifySuccessfulWorkerRun(run.id, () => run), run);
  for (const changed of [
    { id: run.id + 1 }, { workflow_id: 1 }, { path: ".github/workflows/other.yml" },
    { conclusion: "failure" }, { status: "in_progress" }, { event: "push" },
    { repository: { full_name: "other/repo" } }, { head_repository: { full_name: "other/repo" } },
  ]) assert.throws(() => verifySuccessfulWorkerRun(run.id, () => ({ ...run, ...changed })), /not a completed successful/);
});
