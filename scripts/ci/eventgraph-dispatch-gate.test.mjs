import test from "node:test";
import assert from "node:assert/strict";
import { runGate } from "./eventgraph-dispatch-gate.mjs";
import { countInFlight, getActiveWorkerRuns, IN_FLIGHT_CAP, parseWorkerMarker, verifyPrRunState } from "./eventgraph-work-queue-guards.mjs";

const repository = "jboone1989/EventGraph";

function markerBody(workId, runId) {
  return [
    "## Delivery",
    "",
    `> Generated by [EventGraph GH-AW Worker](https://github.com/${repository}/actions/runs/${runId}) · claude · glm53`,
    `> Work \`${workId}\` · Claim \`c_example_1\``,
    "",
    `<!-- gh-aw-workflow-id: eventgraph-worker -->`,
    `<!-- gh-aw-execution: {"version":1,"repository":"${repository}","aw_workflow_id":"eventgraph-worker","run_id":"${runId}"} -->`,
  ].join("\n");
}

function pr(number, workId, runId, overrides = {}) {
  return {
    number, state: "open", draft: false, labels: [{ name: "agent-work" }],
    base: { ref: "develop", repo: { full_name: repository } },
    head: { ref: `agent/work-${number}`, sha: `${number}`.padStart(40, "a").slice(0, 40), repo: { full_name: repository } },
    body: markerBody(workId, runId),
    ...overrides,
  };
}

function activeRun(id) {
  return {
    id, workflow_id: 401548383, path: ".github/workflows/eventgraph-worker.lock.yml",
    event: "workflow_dispatch", status: "in_progress", conclusion: null,
    repository: { full_name: repository }, head_repository: { full_name: repository },
  };
}

function gate({ prs = [], runs = [], prRun = () => ({ status: "completed", conclusion: "success" }) } = {}) {
  const calls = [];
  const result = runGate({
    getOpenAgentWorkPrs: () => prs,
    getActiveWorkerRuns: () => runs,
    verifyPrRunState: (runId) => ({ id: runId, ...prRun(runId) }),
    dispatchNext: () => calls.push("dispatch"),
  });
  return { result, calls };
}

test("countInFlight merges a run and the PR it staged into one Work identity", () => {
  assert.equal(countInFlight([], []).count, 0);
  assert.equal(countInFlight([activeRun(1)], []).count, 1);
  assert.equal(countInFlight([activeRun(1)], [{ runId: "1", workId: "w1", prNumber: 41 }]).count, 1);
  assert.equal(countInFlight(
    [activeRun(1), activeRun(2)],
    [{ runId: "1", workId: "w1", prNumber: 41 }, { runId: "2", workId: "w2", prNumber: 42 }],
  ).count, 2);
});

test("countInFlight merges retries of one Work across different runs by Work ID", () => {
  const { count, groups } = countInFlight(
    [activeRun(1), activeRun(2)],
    [{ runId: "1", workId: "same", prNumber: 41 }, { runId: "2", workId: "same", prNumber: 42 }],
  );
  assert.equal(count, 1);
  assert.deepEqual(groups[0].runIds.sort(), ["1", "2"]);
  assert.deepEqual(groups[0].prNumbers.sort(), [41, 42]);
});

test("the gate dispatches at 0 and 1 in-flight Works and pauses exactly at the cap", () => {
  assert.equal(IN_FLIGHT_CAP, 2);
  const empty = gate();
  assert.equal(empty.result, "dispatched");
  assert.deepEqual(empty.calls, ["dispatch"]);

  const onePr = gate({ prs: [pr(41, "w1", 111)] });
  assert.equal(onePr.result, "dispatched");
  assert.deepEqual(onePr.calls, ["dispatch"]);

  const oneRun = gate({ runs: [activeRun(9)] });
  assert.equal(oneRun.result, "dispatched");

  const twoPrs = gate({ prs: [pr(41, "w1", 111), pr(42, "w2", 222)] });
  assert.equal(twoPrs.result, "paused");
  assert.deepEqual(twoPrs.calls, []);

  const prAndRun = gate({ prs: [pr(41, "w1", 111)], runs: [activeRun(222)] });
  assert.equal(prAndRun.result, "paused");
  assert.deepEqual(prAndRun.calls, []);

  const merged = gate({ prs: [pr(41, "w1", 111)], runs: [activeRun(111)] });
  assert.equal(merged.result, "dispatched");
  assert.deepEqual(merged.calls, ["dispatch"]);
});

test("over-cap in-flight state fails closed instead of dispatching", () => {
  for (const state of [
    { prs: [pr(41, "w1", 111), pr(42, "w2", 222), pr(43, "w3", 333)] },
    { prs: [pr(41, "w1", 111), pr(42, "w2", 222)], runs: [activeRun(333)] },
    { runs: [activeRun(1), activeRun(2), activeRun(3)] },
  ]) {
    const calls = [];
    assert.throws(() => runGate({
      getOpenAgentWorkPrs: () => state.prs ?? [],
      getActiveWorkerRuns: () => state.runs ?? [],
      verifyPrRunState: () => ({ status: "completed", conclusion: "success" }),
      dispatchNext: () => calls.push("dispatch"),
    }), /exceed the cap of 2/);
    assert.deepEqual(calls, []);
  }
});

test("unprovable in-flight state fails closed: invalid markers and failed backing runs", () => {
  const calls = [];
  const inject = (prs, prRun) => () => runGate({
    getOpenAgentWorkPrs: () => prs,
    getActiveWorkerRuns: () => [],
    verifyPrRunState: prRun,
    dispatchNext: () => calls.push("dispatch"),
  });
  assert.throws(inject(
    [pr(41, "w1", 111, { body: "## Delivery\nno marker" })],
    () => ({ status: "completed", conclusion: "success" }),
  ), /no valid Work\/Worker marker/);
  assert.throws(inject(
    [pr(41, "w1", 111, { draft: true })],
    () => ({ status: "completed", conclusion: "success" }),
  ), /violates repository, branch, base, label, or draft policy/);
  assert.throws(inject(
    [pr(41, "w1", 111)],
    () => { throw new Error("Open agent-work PR references Worker run 111, which already failed"); },
  ), /already failed/);
  assert.deepEqual(calls, []);
});

test("verifyPrRunState accepts finished-success and still-running runs, rejects failures", () => {
  const read = run => () => ({ ...activeRun(111), ...run });
  assert.equal(verifyPrRunState("111", read({ status: "completed", conclusion: "success" })).id, 111);
  assert.equal(verifyPrRunState("111", read({ status: "in_progress" })).id, 111);
  for (const changed of [
    { id: 112 }, { workflow_id: 1 }, { event: "push" },
    { status: "completed", conclusion: "failure" },
    { repository: { full_name: "other/repo" } },
  ]) {
    assert.throws(() => verifyPrRunState("111", read(changed)), /references (run|Worker run) 111/);
  }
});

test("two Worker runs map to two distinct PR identities without double counting", () => {
  const prA = pr(41, "aaaa", 111);
  const prB = pr(42, "bbbb", 222);
  assert.deepEqual(parseWorkerMarker(prA.body), { workId: "aaaa", runId: "111" });
  assert.deepEqual(parseWorkerMarker(prB.body), { workId: "bbbb", runId: "222" });
  const { result, calls } = gate({ prs: [prA, prB] });
  assert.equal(result, "paused");
  assert.deepEqual(calls, []);
});

test("the gate snapshots active runs before open PRs to close the staging race", () => {
  const order = [];
  runGate({
    getActiveWorkerRuns: () => { order.push("runs"); return []; },
    getOpenAgentWorkPrs: () => { order.push("prs"); return []; },
    dispatchNext: () => order.push("dispatch"),
  });
  // A Work stages its PR before its run ends, so only this order keeps a
  // mid-staging Work visible to at least one of the two snapshots.
  assert.deepEqual(order, ["runs", "prs", "dispatch"]);
});

test("active Worker runs are listed with an explicit GET", () => {
  // gh api defaults to POST once -f fields are present, and the workflow-runs
  // endpoint rejects anything but GET.
  const calls = [];
  getActiveWorkerRuns((args) => { calls.push(args); return { workflow_runs: [] }; });
  assert.deepEqual(calls, [[
    "api", "--method", "GET",
    "repos/jboone1989/EventGraph/actions/workflows/401548383/runs",
    "-f", "per_page=100",
  ]]);
});
